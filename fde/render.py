def render_all(project: Project) -> Dict[str, str]:
    """Render every owned file.

    Args:
        project: The loaded project.

    Returns:
        Relative path -> file content.
    """
    out: Dict[str, str] = {}
    lakehouse = project.config.silver_lakehouse
    for model in project.silver():
        name = notebook_name(model)
        out[f"fabric/{name}.Notebook/notebook-content.py"] = _notebook(
            _silver_cells(project, model), lakehouse,
            project.config.silver_wheel)
        out[f"fabric/{name}.Notebook/.platform"] = _platform(
            project, "Notebook", name, f"Silver load of {model.key}.")
    out["fabric/nb_ops_run_silver.Notebook/notebook-content.py"] = _notebook(
        _ops_silver_cells(project), lakehouse, project.config.silver_wheel)
    out["fabric/nb_ops_run_silver.Notebook/.platform"] = _platform(
        project, "Notebook", "nb_ops_run_silver",
        "Runs every silver notebook, then refreshes the SQL endpoint.")
    out["fabric/parameter.yml"] = parameter_yml(project)
    out.update(semantic.render_semantic_model(project, _platform))
    out.update(agent.render_agents(project, _platform))
    for model in project.gold():
        base = f"gold/{model.schema}"
        out[f"{base}/tables/{model.name}.sql"] = gold_table_sql(project, model)
        out[f"{base}/views/{model.name}Source.sql"] = gold_view_sql(project,
                                                                   model)
        out[f"{base}/procedures/Load{model.name}.sql"] = gold_procedure_sql(
            project, model)
    out["gold/ops/tables/DataQualityResult.sql"] = ops_table_sql()
    out["gold/ops/procedures/RunDataQualityTests.sql"] = ops_tests_sql(project)
    out["gold/ops/procedures/RunGoldLoads.sql"] = ops_gold_loads_sql(project)
    return out


def owned_files(root: Path) -> List[str]:
    """Return the rendered files currently on disk.

    Args:
        root: Project root folder.

    Returns:
        Relative paths with forward slashes.
    """
    found = set()
    for pattern in OWNED_GLOBS:
        for path in root.glob(pattern):
            if path.is_file():
                found.add(path.relative_to(root).as_posix())
    return sorted(found)


def write(project: Project, check: bool = False) -> List[str]:
    """Write the rendered files, or report what is out of date.

    Args:
        project: The loaded project.
        check: When True, change nothing and only report.

    Returns:
        Messages: files written / out of date / removed / stale.
    """
    root = project.config.root
    rendered = render_all(project)
    messages = []
    for path, content in sorted(rendered.items()):
        target = root / path
        current = target.read_text(encoding="utf-8") if target.exists() \
            else None
        if current == content:
            continue
        messages.append(f"{'out of date' if check else 'wrote'}: {path}")
        if not check:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8", newline="\n")
    for path in owned_files(root):
        if path not in rendered:
            messages.append(f"{'stale' if check else 'removed'}: {path}")
            if not check:
                stale = root / path
                stale.unlink()
                for folder in stale.parents:
                    if folder == root or any(folder.iterdir()):
                        break
                    folder.rmdir()
    return messages
