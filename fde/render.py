"""Render the code Fabric runs from the specs.

Rendered files are owned by this module: never edit them by hand. Change
the spec (``models/**.yml``) or its SELECT (``models/**.sql``) and run
``python -m fde render``. ``python -m fde render --check`` fails when a
rendered file is out of date, so CI catches hand edits.

Rendered output:

* ``fabric/nb_silver_<schema>_<table>.Notebook/``: one PySpark notebook per
  silver table (Fabric Git format: ``notebook-content.py`` + ``.platform``).
* ``fabric/nb_ops_run_silver.Notebook/``: runs every silver notebook in
  dependency order, then refreshes the silver SQL endpoint.
* ``fabric/parameter.yml``: fabric-cicd replacements per environment.
* ``fabric/<sm>.SemanticModel/``: the Direct Lake semantic model (TMDL), see
  ``fde/semantic.py``.
* ``fabric/da_<name>.DataAgent/``: one Fabric Data Agent per
  ``models/agents/<Name>.yml``, see ``fde/agent.py``.
* ``gold/<schema>/tables|views|procedures/*.sql``: one table, one source
  view and one load procedure per gold table.
* ``gold/ops/...``: the data quality log table and procedures, and the
  procedure that runs every gold load in order.
"""

