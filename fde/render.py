def _q(name: str) -> str:
    """Bracket-quote a T-SQL identifier.

    Args:
        name: Identifier.

    Returns:
        ``[name]``.
    """
    return "[" + name.replace("]", "]]") + "]"


def _unknown_literal(data_type: str) -> str:
    """Return the business key value used for the unknown member row.

    Args:
        data_type: Fabric Warehouse type of the key.

    Returns:
        A T-SQL literal.
    """
    base = data_type.split("(")[0]
    if base in ("varchar", "char"):
        return "'-1'"
    if base in ("date", "datetime2"):
        return "'1900-01-01'"
    if base == "bit":
        return "0"
    if base == "uniqueidentifier":
        return "'00000000-0000-0000-0000-000000000000'"
    return "-1"


def _gold_columns(model: Model) -> List[Tuple[str, str, bool]]:
    """Return every physical column of a gold table in policy order.

    Args:
        model: A gold model.

    Returns:
        (name, type, nullable) triples: ``_SK``, business keys, data,
        ``StartDate``/``EndDate``/``IsCurrent`` (type 2 only), audit.
    """
    cols = [(model.surrogate_key, "bigint", False)]
    cols += [(c.name, c.data_type, False) for c in model.columns
             if c.business_key]
    cols += [(c.name, c.data_type, True) for c in model.data_columns]
    if model.is_scd2:
        cols += [("StartDate", "date", False), ("EndDate", "date", False),
                 ("IsCurrent", "bit", False)]
    cols += [(n, t, False) for n, t in TSQL_AUDIT]
    return cols


def _schema_batch(schema: str) -> str:
    """Return a batch that creates a schema when it is missing.

    Args:
        schema: Schema name.

    Returns:
        T-SQL ending in ``GO``.
    """
    return (f"IF SCHEMA_ID('{schema}') IS NULL\n"
            f"    EXEC('CREATE SCHEMA {_q(schema)}');\nGO\n")


def gold_table_sql(project: Project, model: Model) -> str:
    """Return the idempotent DDL of a gold table.

    Creates the table when missing, adds columns added to the spec since,
    declares the informational primary key and inserts the unknown member
    row of a dimension.

    Args:
        project: The loaded project.
        model: A gold model.

    Returns:
        T-SQL batches separated by ``GO``.
    """
    spec = model.path.relative_to(project.config.root).as_posix()
    rel = project.relation(model)
    cols = _gold_columns(model)
    width = max(len(_q(n)) for n, _, _ in cols)
    lines = [f"-- Gold table {model.key} ({model.kind}"
             + (f", SCD type {model.scd_type}" if model.scd_type else "")
             + ").", f"-- {GENERATED.format(spec=spec)}", "",
             _schema_batch(model.schema),
             f"IF OBJECT_ID('{model.schema}.{model.name}') IS NULL",
             f"CREATE TABLE {rel} ("]
    body = [f"    {_q(n).ljust(width)} {t} {'NULL' if null else 'NOT NULL'}"
            for n, t, null in cols]
    lines += [",\n".join(body), ");", "GO", "",
              "-- Columns added to the spec after the first deploy.",
              "-- Fabric can only add nullable columns; type changes need a",
              "-- migration (see the standards, section 7.5)."]
    for name, data_type, nullable in cols:
        if nullable:
            lines += ["IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS",
                      f"               WHERE TABLE_SCHEMA = '{model.schema}'",
                      f"               AND TABLE_NAME = '{model.name}'",
                      f"               AND COLUMN_NAME = '{name}')",
                      f"    ALTER TABLE {rel} ADD {_q(name)} {data_type} NULL;"]
    lines += ["GO", "",
              "-- Informational key (Fabric does not enforce it; the tests do).",
              "IF NOT EXISTS (SELECT 1 FROM sys.key_constraints",
              f"               WHERE name = 'PK_{model.name}')",
              f"    ALTER TABLE {rel} ADD CONSTRAINT {_q('PK_' + model.name)}",
              f"        PRIMARY KEY NONCLUSTERED ({_q(model.surrogate_key)})"
              " NOT ENFORCED;", "GO"]
    if model.kind == "dimension":
        names = [model.surrogate_key] + model.business_keys
        values = ["-1"] + [_unknown_literal(c.data_type)
                           for c in model.columns if c.business_key]
        if model.is_scd2:
            names += ["StartDate", "EndDate", "IsCurrent"]
            values += ["'1900-01-01'", "'9999-12-31'", "1"]
        names += AUDIT_COLUMNS
        values += ["'deploy'", "SYSUTCDATETIME()", "'deploy'",
                   "SYSUTCDATETIME()"]
        lines += ["", "-- Unknown member: facts point here when a key has "
                      "no dimension row.",
                  f"IF NOT EXISTS (SELECT 1 FROM {rel} "
                  f"WHERE {_q(model.surrogate_key)} = -1)",
                  f"    INSERT INTO {rel}",
                  "        (" + ", ".join(_q(n) for n in names) + ")",
                  "    VALUES (" + ", ".join(values) + ");", "GO"]
    return "\n".join(lines) + "\n"


def view_name(model: Model) -> str:
    """Return the name of the source view of a gold table.

    Args:
        model: A gold model.

    Returns:
        ``[stage].[<Table>Source]``.
    """
    return f"[stage].{_q(model.name + 'Source')}"


def gold_view_sql(project: Project, model: Model) -> str:
    """Return the view that holds a gold table's SELECT.

    Args:
        project: The loaded project.
        model: A gold model.

    Returns:
        T-SQL: create the ``stage`` schema, then ``CREATE OR ALTER VIEW``.
    """
    spec = model.path.relative_to(project.config.root).as_posix()
    body = project.resolve_sql(model.sql or "", "tsql").strip()
    body = body.rstrip(";").rstrip()
    return "\n".join([
        f"-- Source rows for {model.key}: the logic of the table.",
        f"-- {GENERATED.format(spec=spec[:-4] + '.sql')}", "",
        _schema_batch("stage"),
        f"CREATE OR ALTER VIEW {view_name(model)}",
        "AS",
        body,
        "GO",
    ]) + "\n"


def _changed(left: str, right: str, columns: List[str],
             indent: str) -> str:
    """Return a null-safe "any column differs" predicate.

    Args:
        left: Alias of one side.
        right: Alias of the other side.
        columns: Columns to compare.
        indent: Indent for continuation lines.

    Returns:
        T-SQL boolean expression.
    """
    parts = []
    for c in columns:
        a, b = f"{left}.{_q(c)}", f"{right}.{_q(c)}"
        parts.append(f"({a} <> {b} OR ({a} IS NULL AND {b} IS NOT NULL) "
                     f"OR ({a} IS NOT NULL AND {b} IS NULL))")
    return f"\n{indent}OR ".join(parts)


def gold_procedure_sql(project: Project, model: Model) -> str:
    """Return the load procedure of a gold table (one per table).

    Type 2 dimensions close the current version of changed rows and insert
    the new version in one MERGE. Facts, bridges and type 1 dimensions
    update changed rows in place and insert new ones.

    Args:
        project: The loaded project.
        model: A gold model.

    Returns:
        T-SQL ending in ``GO``.
    """
    spec = model.path.relative_to(project.config.root).as_posix()
    rel = project.relation(model)
    sk = _q(model.surrogate_key)
    keys = model.business_keys
    data = [c.name for c in model.data_columns]
    order = ", ".join(f"s.{_q(k)}" for k in keys) or "(SELECT NULL)"
    types = {c.name: c.data_type for c in model.columns}
    load = model.load
    where = ""
    if load.get("mode") == "incremental" and load.get("column"):
        where = (f"\n        WHERE s.{_q(str(load['column']))} >= "
                 f"DATEADD(day, -{int(load.get('lookback_days', 0))}, "
                 "@LoadDate)")
    casts = ",\n".join(f"            CAST(s.{_q(c.name)} AS {c.data_type}) "
                       f"AS {_q(c.name)}" for c in model.columns)
    head = [
        f"-- Load {model.key} ({model.kind}"
        + (f", SCD type {model.scd_type}" if model.scd_type else "") + ").",
        "-- One stored procedure per destination table (DE Policy v2, 5.3).",
        f"-- {GENERATED.format(spec=spec)}", "",
        f"CREATE OR ALTER PROCEDURE {_q(model.schema)}."
        f"{_q('Load' + model.name)}",
        "    @LoadDate date,",
        "    @LoadStepID varchar(36)",
        "AS",
        "BEGIN",
        "    SET NOCOUNT ON;",
        "    DECLARE @Now datetime2(6) = SYSUTCDATETIME();",
        f"    DECLARE @MaxKey bigint = (SELECT COALESCE(MAX({sk}), 0)",
        f"                              FROM {rel} WHERE {sk} > 0);", "",
    ]
    insert_cols = [model.surrogate_key] + keys + data
    if model.is_scd2:
        merge_keys = [f"MergeKey{i}" for i in range(1, len(keys) + 1)]
        all_cols = keys + data
        typed = ",\n".join(f"                CAST(s.{_q(c)} AS {types[c]}) "
                           f"AS {_q(c)}" for c in all_cols)
        current = " AND ".join(f"d.{_q(k)} = s.{_q(k)}" for k in keys)
        on = "\n        AND ".join(f"target.{_q(k)} = source.{_q(m)}"
                                   for k, m in zip(keys, merge_keys))
        body = [
            "    -- Every source row is staged on its business key. Changed",
            "    -- rows are staged again with a NULL key, so the MERGE both",
            "    -- closes the current version and inserts the new one.",
            f"    MERGE {rel} AS target",
            "    USING (",
            "        SELECT changes.*,",
            "            @MaxKey + ROW_NUMBER() OVER (ORDER BY "
            + ", ".join(f"changes.{_q(k)}" for k in keys) + ") AS [NewKey]",
            "        FROM (",
            "            SELECT "
            + ", ".join(f"s.{_q(k)} AS {_q(m)}"
                        for k, m in zip(keys, merge_keys)) + ",",
            typed,
            f"            FROM {view_name(model)} AS s" + where.replace(
                "\n        ", "\n            "),
            "            UNION ALL",
            "            SELECT "
            + ", ".join(f"NULL AS {_q(m)}" for m in merge_keys) + ",",
            typed,
            f"            FROM {view_name(model)} AS s",
            f"            INNER JOIN {rel} AS d",
            f"                ON {current} AND d.[IsCurrent] = 1",
            "            WHERE "
            + _changed("d", "s", data, "                ")
            if data else "            WHERE 1 = 0",
            "        ) AS changes",
            "    ) AS source",
            f"    ON {on}",
            "        AND target.[IsCurrent] = 1",
        ]
        if data:
            body += [
                "    WHEN MATCHED AND (",
                "        " + _changed("target", "source", data, "        "),
                "    ) THEN UPDATE SET",
                "        [EndDate] = DATEADD(day, -1, @LoadDate),",
                "        [IsCurrent] = 0,",
                "        [LastUpdateLoadStepID] = @LoadStepID,",
                "        [LastUpdateTimestamp] = @Now",
            ]
        names = insert_cols + ["StartDate", "EndDate", "IsCurrent"] \
            + AUDIT_COLUMNS
        values = (["source.[NewKey]"] + [f"source.{_q(c)}" for c in all_cols]
                  + [f"CASE WHEN source.{_q(merge_keys[0])} IS NULL "
                     "THEN @LoadDate ELSE '1900-01-01' END",
                     "'9999-12-31'", "1", "@LoadStepID", "@Now",
                     "@LoadStepID", "@Now"])
    else:
        on = " AND ".join(f"target.{_q(k)} = source.{_q(k)}" for k in keys)
        body = [
            f"    MERGE {rel} AS target",
            "    USING (",
            "        SELECT",
            casts + ",",
            f"            @MaxKey + ROW_NUMBER() OVER (ORDER BY {order}) "
            "AS [NewKey]",
            f"        FROM {view_name(model)} AS s{where}",
            "    ) AS source",
            f"    ON {on or '1 = 0'}",
        ]
        if data:
            body += [
                "    WHEN MATCHED AND (",
                "        " + _changed("target", "source", data, "        "),
                "    ) THEN UPDATE SET",
            ] + [f"        {_q(c)} = source.{_q(c)}," for c in data] + [
                "        [LastUpdateLoadStepID] = @LoadStepID,",
                "        [LastUpdateTimestamp] = @Now",
            ]
        names = insert_cols + AUDIT_COLUMNS
        values = (["source.[NewKey]"]
                  + [f"source.{_q(c)}" for c in keys + data]
                  + ["@LoadStepID", "@Now", "@LoadStepID", "@Now"])
    body += [
        "    WHEN NOT MATCHED BY TARGET THEN INSERT (",
        "        " + ",\n        ".join(_q(n) for n in names),
        "    ) VALUES (",
        "        " + ",\n        ".join(values),
        "    );",
        "END",
        "GO",
    ]
    return "\n".join(head + body) + "\n"


def ops_table_sql() -> str:
    """Return the DDL of the data quality log table.

    Returns:
        T-SQL batches.
    """
    return "\n".join([
        "-- Data quality results: one row per test per run.",
        f"-- {GENERATED.format(spec='fde/render.py')}", "",
        _schema_batch("ops"),
        "IF OBJECT_ID('ops.DataQualityResult') IS NULL",
        "CREATE TABLE [ops].[DataQualityResult] (",
        "    [LoadStepID]      varchar(36)  NOT NULL,",
        "    [Layer]           varchar(10)  NOT NULL,",
        "    [TableName]       varchar(256) NOT NULL,",
        "    [TestName]        varchar(256) NOT NULL,",
        "    [Severity]        varchar(10)  NOT NULL,",
        "    [FailureCount]    bigint       NOT NULL,",
        "    [TestedTimestamp] datetime2(6) NOT NULL",
        ");",
        "GO",
    ]) + "\n"


def ops_tests_sql(project: Project) -> str:
    """Return ``ops.RunDataQualityTests``, generated from every spec test.

    Args:
        project: The loaded project.

    Returns:
        T-SQL ending in ``GO``.
    """
    lines = [
        "-- Runs every data quality test of one layer, logs the failure",
        "-- counts to ops.DataQualityResult and throws when an error-severity",
        "-- test fails, which stops the pipeline (stale but right beats",
        "-- fresh but wrong).",
        f"-- {GENERATED.format(spec='every spec under models/')}", "",
        "CREATE OR ALTER PROCEDURE [ops].[RunDataQualityTests]",
        "    @Layer varchar(10),",
        "    @LoadStepID varchar(36)",
        "AS",
        "BEGIN",
        "    SET NOCOUNT ON;",
    ]
    for layer in ("source", "silver", "gold"):
        tests = dq.all_tests(project, layer)
        if not tests:
            continue
        lines += ["", f"    IF @Layer = '{layer}'", "    BEGIN"]
        for test in tests:
            lines += [
                f"        -- {test.table}: {test.name}",
                "        INSERT INTO [ops].[DataQualityResult] ([LoadStepID],"
                " [Layer], [TableName],",
                "            [TestName], [Severity], [FailureCount], "
                "[TestedTimestamp])",
                f"        SELECT @LoadStepID, '{layer}', '{test.table}', "
                f"'{test.name}', '{test.severity}',",
                "            COUNT(*), SYSUTCDATETIME()",
                f"        FROM ({dq.failing_rows_sql(project, test)}) "
                "AS failing;",
            ]
        lines += ["    END;"]
    lines += [
        "",
        "    DECLARE @Failed int = (",
        "        SELECT COUNT(*) FROM [ops].[DataQualityResult]",
        "        WHERE [LoadStepID] = @LoadStepID AND [Layer] = @Layer",
        "            AND [Severity] = 'error' AND [FailureCount] > 0",
        "    );",
        "    IF @Failed > 0",
        "    BEGIN",
        "        DECLARE @Message varchar(400) = CONCAT(@Failed, ' ', @Layer,",
        "            ' data quality test(s) failed. See ops.DataQualityResult',",
        "            ' for LoadStepID ', @LoadStepID, '.');",
        "        THROW 50001, @Message, 1;",
        "    END;",
        "END",
        "GO",
    ]
    return "\n".join(lines) + "\n"


def ops_gold_loads_sql(project: Project) -> str:
    """Return ``ops.RunGoldLoads``: every gold load in dependency order.

    Args:
        project: The loaded project.

    Returns:
        T-SQL ending in ``GO``.
    """
    lines = [
        "-- Runs every gold load procedure: dimensions first, then the",
        "-- tables that read them. Step 4 of the daily pipeline.",
        f"-- {GENERATED.format(spec='every gold spec')}", "",
        "CREATE OR ALTER PROCEDURE [ops].[RunGoldLoads]",
        "    @LoadDate date,",
        "    @LoadStepID varchar(36)",
        "AS",
        "BEGIN",
        "    SET NOCOUNT ON;",
    ]
    for model in project.load_order(project.gold()):
        lines.append(f"    EXEC {_q(model.schema)}.{_q('Load' + model.name)}"
                     " @LoadDate = @LoadDate, @LoadStepID = @LoadStepID;")
    lines += ["END", "GO"]
    return "\n".join(lines) + "\n"


def parameter_yml(project: Project) -> str:
    """Return the fabric-cicd ``parameter.yml``.

    Rendered notebooks carry placeholder ids for their default lakehouse;
    fabric-cicd swaps them for the real ids of the target workspace.

    Args:
        project: The loaded project.

    Returns:
        YAML text.
    """
    lakehouse = project.config.silver_lakehouse
    envs = ["DEV", "TEST", "PROD"]
    lines = [f"# {GENERATED.format(spec='fde.yml')}",
             "# Used by fabric-cicd when `python -m fde deploy` publishes",
             "# the notebooks, semantic model and data agents. [Spike] confirm",
             "# the dynamic replacement",
             "# syntax for the fabric-cicd version you pin.",
             "find_replace:"]
    for find, value in [(WORKSPACE_PLACEHOLDER, "$workspace.id"),
                        (LAKEHOUSE_PLACEHOLDER,
                         f"$items.Lakehouse.{lakehouse}.id")]:
        lines += [f'  - find_value: "{find}"', "    replace_value:"]
        lines += [f'      {env}: "{value}"' for env in envs]
        lines += ['    item_type: "Notebook"']
    if project.gold():
        warehouse = project.config.gold_warehouse
        for find, value, item_type in [
                (semantic.SQL_ENDPOINT_PLACEHOLDER,
                 f"$items.Warehouse.{warehouse}.sqlendpoint",
                 "SemanticModel"),
                (semantic.WAREHOUSE_PLACEHOLDER,
                 f"$items.Warehouse.{warehouse}.id", "SemanticModel")]:
            lines += [f'  - find_value: "{find}"', "    replace_value:"]
            lines += [f'      {env}: "{value}"' for env in envs]
            lines += [f'    item_type: "{item_type}"']
    if project.agents:
        warehouse = project.config.gold_warehouse
        model = project.config.semantic_model
        for find, value in [
                (WORKSPACE_PLACEHOLDER, "$workspace.id"),
                (semantic.WAREHOUSE_PLACEHOLDER,
                 f"$items.Warehouse.{warehouse}.id"),
                (semantic.SEMANTIC_MODEL_PLACEHOLDER,
                 f"$items.SemanticModel.{model}.id")]:
            lines += [f'  - find_value: "{find}"', "    replace_value:"]
            lines += [f'      {env}: "{value}"' for env in envs]
            lines += ['    item_type: "DataAgent"']
    return "\n".join(lines) + "\n"


