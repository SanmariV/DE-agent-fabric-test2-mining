def _meta(obj: dict) -> str:
    """Return a ``# META`` block for a notebook or cell.

    Args:
        obj: Metadata to serialise.

    Returns:
        The JSON, each line prefixed with ``# META``.
    """
    return "\n".join("# META " + line if line else "# META"
                     for line in json.dumps(obj, indent=2).splitlines())


def _install_cell(wheel: str) -> Tuple[str, str]:
    """Return a cell that installs ``fabric_de_common`` if it is missing.

    A plain Python cell (not ``%pip``) so it also works when the notebook is
    run by ``runMultiple``, and does nothing when the parent already
    installed the library.

    Args:
        wheel: Path of the wheel, e.g. under ``/lakehouse/default/Files``.

    Returns:
        A (kind, text) cell.
    """
    return ("code", "\n".join([
        "# Install the shared library for this session only (no Environment).",
        "import importlib",
        "import importlib.util",
        "import subprocess",
        "import sys",
        "",
        f"COMMON_WHEEL = {wheel!r}",
        "if importlib.util.find_spec(\"fabric_de_common\") is None:",
        "    subprocess.check_call(",
        "        [sys.executable, \"-m\", \"pip\", \"install\", \"-q\", COMMON_WHEEL])",
        "    importlib.invalidate_caches()",
    ]))


def _notebook(cells: List[Tuple[str, str]], lakehouse: str,
              wheel: str = "") -> str:
    """Return ``notebook-content.py`` in the Fabric Git source format.

    Args:
        cells: (kind, text) pairs; kind is ``markdown``, ``parameters`` or
            ``code``.
        lakehouse: Default lakehouse name for the notebook.
        wheel: If set, a first code cell installs the library from this
            path.

    Returns:
        The file content.
    """
    if wheel:
        first = next((i for i, (kind, _) in enumerate(cells)
                      if kind != "markdown"), len(cells))
        cells = cells[:first] + [_install_cell(wheel)] + cells[first:]
    header = {
        "kernel_info": {"name": "synapse_pyspark"},
        "dependencies": {"lakehouse": {
            "default_lakehouse": LAKEHOUSE_PLACEHOLDER,
            "default_lakehouse_name": lakehouse,
            "default_lakehouse_workspace_id": WORKSPACE_PLACEHOLDER,
        }},
    }
    parts = ["# Fabric notebook source", "",
             "# METADATA ********************", "", _meta(header), ""]
    for kind, text in cells:
        if kind == "markdown":
            body = "\n".join("# " + line if line else "#"
                             for line in text.strip("\n").splitlines())
            parts += ["# MARKDOWN ********************", "", body, ""]
            continue
        marker = ("# PARAMETERS CELL ********************"
                  if kind == "parameters" else "# CELL ********************")
        parts += [marker, "", text.strip("\n"), "",
                  "# METADATA ********************", "", _meta(CELL_META), ""]
    return "\n".join(parts)


def _platform(project: Project, item_type: str, name: str,
              description: str) -> str:
    """Return the ``.platform`` file of a Fabric item.

    Args:
        project: The loaded project.
        item_type: Fabric item type, e.g. ``Notebook``.
        name: Item display name.
        description: Item description.

    Returns:
        The JSON text. The logical id is derived from the name, so it is
        the same on every render.
    """
    logical = uuid.uuid5(uuid.NAMESPACE_URL,
                         f"fde:{project.config.project}:{item_type}:{name}")
    return json.dumps({
        "$schema": ("https://developer.microsoft.com/json-schemas/fabric/"
                    "gitIntegration/platformProperties/2.0.0/schema.json"),
        "metadata": {"type": item_type, "displayName": name,
                     "description": description[:250]},
        "config": {"version": "2.0", "logicalId": str(logical)},
    }, indent=2) + "\n"


def notebook_name(model: Model) -> str:
    """Return the Fabric notebook name of a silver model.

    Args:
        model: A silver model.

    Returns:
        ``nb_silver_<schema>_<table_in_snake_case>``.
    """
    return f"nb_silver_{model.schema}_{snake(model.name)}"


def _py_list(name: str, items: List[str], indent: str = "    ") -> str:
    """Return a Python list assignment, one item per line.

    Args:
        name: Variable name.
        items: Python literals (already repr'd).
        indent: Indent for the items.

    Returns:
        Source code.
    """
    if not items:
        return f"{name} = []"
    return "\n".join([f"{name} = ["] + [f"{indent}{i}," for i in items]
                     + ["]"])


def _column_tuples(model: Model, use_expression: bool) -> List[str]:
    """Return ``(name, type, expression)`` tuples as Python literals.

    Args:
        model: A silver model.
        use_expression: True for source tables (expression over bronze);
            False for integrated tables (the query column of the same name).

    Returns:
        One literal per column, wrapped when longer than a line.
    """
    out = []
    for col in model.columns:
        expr = (col.expression or col.name) if use_expression else col.name
        one = f"({col.name!r}, {col.data_type!r}, {str(expr)!r})"
        if len(one) <= 72:
            out.append(one)
        else:
            out.append("(\n        " + ",\n        ".join(
                [repr(col.name), repr(col.data_type), repr(str(expr))])
                + ",\n    )")
    return out


def _py_str(name: str, text: str, width: int = 60) -> str:
    """Return ``NAME = "..."`` wrapped in parentheses when it is long.

    Args:
        name: Variable name.
        text: String value.
        width: Maximum characters per chunk.

    Returns:
        Source code that keeps lines short (PEP 8).
    """
    if len(name) + len(repr(text)) + 3 <= 79:
        return f"{name} = {text!r}"
    words, chunks, line = text.split(" "), [], ""
    for word in words:
        if line and len(line) + len(word) + 1 > width:
            chunks.append(line + " ")
            line = word
        else:
            line = f"{line} {word}" if line else word
    chunks.append(line)
    body = "\n".join(f"    {c!r}" for c in chunks)
    return f"{name} = (\n{body}\n)"


