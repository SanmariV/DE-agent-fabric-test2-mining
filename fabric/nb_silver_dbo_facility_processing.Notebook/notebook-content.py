# ## Load
#
# Read bronze, rename and cast every column, keep the latest row per business key, then MERGE into silver.

# CELL ********************

def main(load_date: str, load_step_id: str, full_refresh: bool) -> int:
    """Merge one day of bronze rows into the silver table.

    Args:
        load_date: Business date being loaded (``yyyy-mm-dd``); empty means
            yesterday (UTC).
        load_step_id: Load step identifier written to the audit columns.
        full_refresh: Read the whole bronze table instead of the
            incremental window.

    Returns:
        The number of distinct business keys merged.
    """
    bronze = silver.read_bronze(
        spark, SOURCE_TABLE, BRONZE_COLUMNS,
        watermark_column=None if full_refresh else WATERMARK_COLUMN,
        load_date=silver.resolve_load_date(load_date),
        lookback_days=LOOKBACK_DAYS)
    conformed = silver.conform(bronze, COLUMNS, DEDUPE_ORDER_BY)
    latest = silver.latest_per_key(conformed, BUSINESS_KEYS)
    silver.ensure_table(spark, TARGET_TABLE, COLUMNS, BUSINESS_KEYS,
                        DESCRIPTION)
    return silver.merge_into(spark, TARGET_TABLE, latest, BUSINESS_KEYS,
                             load_step_id)

