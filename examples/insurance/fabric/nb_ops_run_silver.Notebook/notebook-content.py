def build_dag(load_date: str, load_step_id: str,
              full_refresh: str) -> dict:
    """Return the runMultiple DAG for every silver notebook.

    Args:
        load_date: Business date passed to every notebook.
        load_step_id: Load step identifier passed to every notebook.
        full_refresh: ``true`` to make source notebooks read all of bronze.

    Returns:
        A ``notebookutils.notebook.runMultiple`` DAG.
    """
    args = {"load_date": load_date, "load_step_id": load_step_id,
            "full_refresh": full_refresh}
    return {
        "activities": [
            {"name": name, "path": name, "args": args,
             "timeoutPerCellInSeconds": 3600, "dependencies": deps}
            for name, deps in NOTEBOOKS],
        "concurrency": CONCURRENCY,
    }


def main(load_date: str, load_step_id: str, full_refresh: str) -> None:
    """Run every silver notebook, then refresh the silver SQL endpoint.

    The refresh makes the new rows visible to the Warehouse, which reads
    silver through the SQL endpoint for the silver tests and gold loads.

    Args:
        load_date: Business date passed to every notebook.
        load_step_id: Load step identifier passed to every notebook.
        full_refresh: ``true`` to make source notebooks read all of bronze.
    """
    if NOTEBOOKS:
        notebookutils.notebook.runMultiple(
            build_dag(load_date, load_step_id, full_refresh))
    ops.refresh_sql_endpoint(SILVER_LAKEHOUSE)

